import assert from "node:assert/strict";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { ModifiedStar } from "../plugins/modified-star/index.js";
import { createApp } from "../src/assembly/createApp.js";
import { Group } from "../src/core/Group.js";
import { SvgDocument } from "../src/core/SvgDocument.js";
import { Rect } from "../src/shapes/Rect.js";

test("modified-star checkpoints track current content and keep state per decorator instance", () => {
  const star = new ModifiedStar();
  const other = new ModifiedStar();
  const doc = new SvgDocument(200, 100);
  const group = new Group("group");
  const rect = new Rect("rect", 0, 0, 10, 10, "red");
  doc.add(group);
  doc.add(rect, group.id);
  assert.equal(star.label(doc), "*");
  assert.equal(star.label(doc, rect), "*");
  star.onSaved(doc);
  assert.equal(star.label(doc), undefined);
  assert.equal(star.label(doc, rect), undefined);
  assert.equal(other.label(doc, rect), "*");
  rect.setAttribute("fill", "blue");
  assert.equal(star.label(doc), "*");
  assert.equal(star.label(doc, rect), "*");
  assert.equal(star.label(doc, group), undefined);
  rect.setAttribute("fill", "red");
  assert.equal(star.label(doc), undefined);
  assert.equal(star.label(doc, rect), undefined);
  doc.delete(rect);
  assert.equal(star.label(doc, group), "*");
  doc.restore(rect, group);
  assert.equal(star.label(doc, group), undefined);
  assert.equal(star.label(doc), undefined);
});

test("tree shows both labels and undo/redo can return to the save point", async (t) => {
  const scratch = mkdtempSync(join(tmpdir(), "svg-star-"));
  t.after(() => rmSync(scratch, { recursive: true, force: true }));
  const path = join(scratch, "checkpoint.svg");
  const app = await createApp();
  const run = (line: string) => app.evalLine(line)!;
  run("init");
  assert.equal(run("tree"), "svg (800x600) *");
  run('create box n1 120 100 160 60 "Start"');
  assert.match(run("tree n1"), /^g#n1 \(box\) \*$/m);
  assert.match(run("tree n1"), /rect#n1-rect.* \*$/m);
  assert.match(run(`save "${path}"`), /^saved to /);
  const clean = run("tree");
  assert.match(clean, /g#n1 \(box\)$/m);
  assert.doesNotMatch(clean, / \*$/m);
  assert.match(run("set n1 fill blue"), /fill propagated/);
  const edited = run("tree");
  assert.match(edited, /^svg \(800x600\) \*$/m);
  assert.match(edited, /g#n1 \(box\)$/m);
  assert.match(edited, /rect#n1-rect.*fill=blue \*$/m);
  run("undo");
  assert.equal(run("tree"), clean);
  run("redo");
  assert.equal(run("tree"), edited);
  assert.match(run(`read "${path}"`), /^read /);
  assert.equal(run("tree"), clean);

  const empty = join(scratch, "empty.json");
  writeFileSync(empty, '{"plugins":[]}');
  const plain = await createApp(empty);
  plain.evalLine(`read "${path}"`);
  plain.evalLine("set n1-rect fill blue");
  assert.doesNotMatch(plain.evalLine("tree")!, / \*|\(box\)/);
});
